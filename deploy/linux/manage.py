"""Server-side preparation helpers. Never print credentials or candidate content."""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import re
import secrets
import shlex
import shutil
import subprocess
import sys
from urllib.error import HTTPError
from urllib.parse import unquote, urlsplit
from urllib.request import Request, urlopen

ENV_FILE = Path('/etc/interview-copilot/production.env')
BACKUP_ROOT = Path('/var/backups/interview-copilot')
STATE_ROOT = Path('/var/lib/interview-copilot')
REQUIRED = ('FEISHU_APP_ID', 'FEISHU_APP_SECRET', 'FEISHU_ADMIN_OPEN_IDS',
            'INTERVIEW_LLM_API_KEY', 'TENCENT_ASR_APP_ID',
            'TENCENT_ASR_SECRET_ID', 'TENCENT_ASR_SECRET_KEY')


def read_env(path: Path = ENV_FILE) -> dict[str, str]:
    result = {}
    for line in path.read_text(encoding='utf-8').splitlines():
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        key, sep, value = line.partition('=')
        if not sep or not re.fullmatch(r'[A-Z][A-Z0-9_]*', key):
            raise ValueError('Invalid environment entry; values are not displayed')
        parts = shlex.split(value, comments=False)
        if len(parts) > 1:
            raise ValueError('Quote environment values containing spaces')
        result[key] = parts[0] if parts else ''
    return result


def init_env(template: Path, target: Path = ENV_FILE) -> bool:
    """Exclusive creation; a repeated run never replaces existing secrets."""
    content = template.read_text(encoding='utf-8')
    password = secrets.token_hex(24)
    content = content.replace('INTERVIEW_DATABASE_URL=GENERATED_ON_SERVER',
                              'INTERVIEW_DATABASE_URL=postgresql+psycopg://'
                              f'interview_copilot:{password}@127.0.0.1:5432/interview_copilot')
    content = content.replace('INTERVIEW_SESSION_SECRET=GENERATED_ON_SERVER',
                              f'INTERVIEW_SESSION_SECRET={secrets.token_hex(48)}')
    target.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    try:
        fd = os.open(target, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
    except FileExistsError:
        return False
    with os.fdopen(fd, 'w', encoding='utf-8', newline='\n') as stream:
        stream.write(content)
    return True


def pg_environment(config: dict[str, str]) -> dict[str, str]:
    parsed = urlsplit(config['INTERVIEW_DATABASE_URL'])
    if (parsed.scheme != 'postgresql+psycopg' or parsed.hostname != '127.0.0.1'
            or parsed.username != 'interview_copilot'
            or parsed.path != '/interview_copilot' or parsed.query):
        raise ValueError('Expected the dedicated local pilot database')
    return dict(os.environ, PGHOST='127.0.0.1', PGPORT=str(parsed.port or 5432),
                PGUSER='interview_copilot', PGDATABASE='interview_copilot',
                PGPASSWORD=unquote(parsed.password or ''))


def run(command: list[str], **kwargs) -> subprocess.CompletedProcess:
    # Keep stdout/stderr private: database errors can include SQL/credentials.
    result = subprocess.run(command, capture_output=True, timeout=1200, **kwargs)
    if result.returncode:
        raise RuntimeError(f'{Path(command[0]).name} failed (exit {result.returncode}); inspect locally')
    return result


def init_database(config: dict[str, str]) -> None:
    env = pg_environment(config)
    password = env['PGPASSWORD']
    if not re.fullmatch(r'[a-f0-9]{48}', password):
        raise ValueError('Initial database password must be generated by init-env')
    psql = ['runuser', '-u', 'postgres', '--', 'psql', '-X', '-v', 'ON_ERROR_STOP=1', '-At']
    existing = run(psql + ['-c', "SELECT 1 FROM pg_roles WHERE rolname='interview_copilot'"]).stdout.strip()
    if not existing:
        run(psql, input=(f"CREATE ROLE interview_copilot LOGIN PASSWORD '{password}';\n").encode())
    exists_db = run(psql + ['-c', "SELECT 1 FROM pg_database WHERE datname='interview_copilot'"]).stdout.strip()
    if not exists_db:
        run(['runuser', '-u', 'postgres', '--', 'createdb', '-O', 'interview_copilot', 'interview_copilot'])
    run(['psql', '-X', '-v', 'ON_ERROR_STOP=1', '-At', '-c', 'SELECT 1'], env=env)
    print('DATABASE_AUTH_OK')


def http_result(base: str, path: str, *, post: bool = False) -> tuple[int, bytes]:
    request = Request(base + path, data=b'{}' if post else None,
                      headers={'Content-Type': 'application/json'})
    try:
        with urlopen(request, timeout=10) as response:
            return response.status, response.read()
    except HTTPError as error:
        return error.code, error.read()


def smoke(base: str) -> dict:
    parsed = urlsplit(base)
    if parsed.scheme != 'http' or parsed.hostname != '127.0.0.1' or parsed.path:
        raise ValueError('Preparation smoke checks must use the loopback address')
    checks = {}
    for path, expected in [('/', 200), ('/static/job-assessment.js', 200),
                            ('/api/v1/health', 200), ('/api/v1/admin/jobs', 401)]:
        status, _ = http_result(base, path)
        checks[path] = status == expected
    status, body = http_result(base, '/api/v1/auth/status')
    checks['development_login_disabled'] = status == 200 and not json.loads(body)['development_login_available']
    status, _ = http_result(base, '/api/v1/auth/dev-login', post=True)
    checks['preview_login_rejected'] = status == 404
    status, body = http_result(base, '/api/v1/capabilities')
    capabilities = json.loads(body)
    checks['pipecat_installed'] = status == 200 and capabilities['pipecat']['installed']
    checks['automatic_hiring_disabled'] = not capabilities['automatic_hiring_decision']
    checks['automatic_stage_change_disabled'] = not capabilities['automatic_stage_change']
    if not all(checks.values()):
        raise RuntimeError('SMOKE_FAILED: ' + ', '.join(key for key, passed in checks.items() if not passed))
    print(json.dumps({'smoke': checks}, ensure_ascii=False))
    return checks


def configuration_status(config: dict[str, str]) -> dict:
    """Presence only; not a paid API or external identity test."""
    result = {'configured': [key for key in REQUIRED if config.get(key)],
              'missing': [key for key in REQUIRED if not config.get(key)],
              'external_api_tests_performed': False}
    print(json.dumps(result, ensure_ascii=False))
    return result


def backup(config: dict[str, str], root: Path = BACKUP_ROOT, state: Path = STATE_ROOT) -> Path:
    """pg_dump plus immutable rsync snapshots; no source deletion or retention pruning."""
    root.mkdir(mode=0o700, parents=True, exist_ok=True)
    if shutil.disk_usage(root).free < 2 * 1024**3:
        raise RuntimeError('Backup refused: less than 2GiB free; no backups deleted')
    stamp = datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ') + '-' + secrets.token_hex(3)
    target = root / stamp
    target.mkdir(mode=0o700)
    previous = root / 'latest'
    previous_target = previous.resolve() if previous.is_symlink() else None
    if previous_target and not previous_target.is_relative_to(root.resolve()):
        raise ValueError('Backup link escaped backup directory')
    dump = target / 'database.dump'
    # --file keeps database content out of command output and Python memory.
    run(['pg_dump', '--format=custom', '--no-owner', '--no-acl', f'--file={dump}'], env=pg_environment(config))
    run(['pg_restore', '--list', str(dump)])
    for name in ('recordings', 'knowledge'):
        source = state / name
        if not source.is_dir():
            raise RuntimeError(f'Backup source missing: {name}')
        command = ['rsync', '-a', '--safe-links']
        if previous_target and (previous_target / name).is_dir():
            command += [f'--link-dest={previous_target / name}']
        run(command + [str(source) + '/', str(target / name) + '/'])
    with dump.open('rb') as stream:
        digest = hashlib.file_digest(stream, 'sha256').hexdigest()
    manifest = {'created_at': stamp, 'database_sha256': digest,
                'database_archive_checked': True, 'restore_drill_performed': False,
                'scope': ['database', 'recordings', 'knowledge'],
                'live_recordings_may_be_incomplete': True,
                'off_server_backup': False, 'credentials_included': False}
    (target / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
    temporary_link = root / f'.latest-{stamp}'
    temporary_link.symlink_to(target.name, target_is_directory=True)
    temporary_link.replace(previous)
    print(f'BACKUP_OK {stamp}; local-only; active audio may be incomplete')
    return target


def verify_backup(root: Path = BACKUP_ROOT) -> None:
    """Restore into a freshly created scratch database; never replace the application DB."""
    target = (root / 'latest').resolve()
    if not target.is_relative_to(root.resolve()) or target == root.resolve():
        raise ValueError('Invalid backup path')
    manifest_path = target / 'manifest.json'
    manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
    dump = target / 'database.dump'
    with dump.open('rb') as stream:
        if hashlib.file_digest(stream, 'sha256').hexdigest() != manifest['database_sha256']:
            raise ValueError('Backup checksum mismatch')
    name = 'interview_verify_' + secrets.token_hex(8)
    run(['runuser', '-u', 'postgres', '--', 'createdb', name])
    try:
        with dump.open('rb') as stream:
            run(['runuser', '-u', 'postgres', '--', 'pg_restore', '--exit-on-error',
                 '--no-owner', '--no-acl', '--single-transaction', '--dbname', name], stdin=stream)
        result = run(['runuser', '-u', 'postgres', '--', 'psql', '-X', '-At', '-d', name,
                      '-c', "SELECT count(*) FROM information_schema.tables WHERE table_schema='public'"])
        count = int(result.stdout.strip())
        if count < 10:
            raise RuntimeError('Restored schema incomplete')
        manifest['restore_drill_performed'] = True
        manifest['restored_table_count'] = count
        manifest_path.write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
        print(f'BACKUP_RESTORE_OK tables={count}; application database untouched')
    finally:
        # Only this invocation's newly-created scratch database is removed.
        run(['runuser', '-u', 'postgres', '--', 'dropdb', name])


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument('action', choices=['init-env', 'init-db', 'status', 'smoke', 'backup', 'verify-backup'])
    parser.add_argument('--template', type=Path, default=Path(__file__).with_name('production.env.example'))
    parser.add_argument('--base-url', default='http://127.0.0.1:8000')
    args = parser.parse_args()
    if args.action == 'init-env':
        print('ENV_CREATED' if init_env(args.template) else 'ENV_PRESERVED')
    elif args.action == 'smoke':
        smoke(args.base_url)
    elif args.action == 'verify-backup':
        verify_backup()
    else:
        config = read_env()
        if args.action == 'init-db':
            init_database(config)
        elif args.action == 'status':
            configuration_status(config)
        else:
            backup(config)
    return 0


if __name__ == '__main__':
    try:
        raise SystemExit(main())
    except (ValueError, RuntimeError, OSError, subprocess.TimeoutExpired) as error:
        # Do not dump environment, provider credentials, or SQL in tracebacks.
        print(f'PREPARATION_FAILED: {type(error).__name__}: check server-local diagnostics', file=sys.stderr)
        raise SystemExit(1)
